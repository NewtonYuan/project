"""Generate responsive, lossless WebP copies; keep every original image."""

from pathlib import Path
import json
from PIL import Image, ImageChops, ImageOps

root = Path(__file__).resolve().parents[1]
images = root / 'public' / 'images'
targets = {
    'annie.jpg': [480, 800, 1200],
    'newton.jpg': [480, 800, 1200],
    'angus.png': [320, 640],
    'deborah.jpg': [320, 640],
    'kevin.png': [320],
    'mason.png': [320, 640],
    'nadi.jpg': [320, 640],
    'phoebe.jpg': [320, 640],
    'markovina-venue.png': [768, 1440],
    'dress-code.jpg': [768],
    'rsvp-portrait.jpg': [480, 960],
}
manifest = {}

for filename, widths in targets.items():
    source = images / filename
    image = ImageOps.exif_transpose(Image.open(source))
    if image.mode not in ('RGB', 'RGBA'):
        image = image.convert('RGBA' if 'transparency' in image.info else 'RGB')
    candidates = {}
    for width in sorted({min(width, image.width) for width in widths}):
        # Match the existing 4:3 profile window and its CSS object-position.
        # Avoid sending portrait pixels that are always hidden by that window.
        if filename in ('annie.jpg', 'newton.jpg'):
            crop_height = image.width * 3 / 4
            position = 0.55 if filename == 'annie.jpg' else 0.60
            top = (image.height - crop_height) * position
            resized = image.resize((width, round(width * 3 / 4)), Image.Resampling.LANCZOS,
                                   box=(0, top, image.width, top + crop_height))
        else:
            height = round(image.height * width / image.width)
            resized = image.resize((width, height), Image.Resampling.LANCZOS)
        output = images / f'{source.stem}-{width}-lossless.webp'
        options = {'lossless': True, 'method': 6, 'exact': True}
        if image.info.get('icc_profile'):
            options['icc_profile'] = image.info['icc_profile']
        resized.save(output, 'WEBP', **options)
        with Image.open(output) as decoded:
            if any(low != 0 or high != 0 for low, high in ImageChops.difference(resized, decoded.convert(resized.mode)).getextrema()):
                raise RuntimeError(f'Lossless pixel verification failed: {output.name}')
        if output.stat().st_size < source.stat().st_size:
            candidates[width] = f'/images/{output.name}'
            print(f'{filename}: {width}px {output.stat().st_size:,} bytes (lossless verified)', flush=True)
        else:
            output.unlink()
    candidates.setdefault(image.width, f'/images/{filename}')
    manifest[f'/images/{filename}'] = {
        'srcSet': ', '.join(f'{url} {width}w' for width, url in sorted(candidates.items())),
        'width': image.width,
        'height': image.height,
    }

(root / 'src' / 'imageVariants.ts').write_text(
    '// Generated by scripts/optimize-images.py; originals remain available.\n'
    'export const imageVariants: Record<string, { srcSet: string; width: number; height: number }> = '
    + json.dumps(manifest, indent=2) + '\n', encoding='utf-8'
)
